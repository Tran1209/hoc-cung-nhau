/**
 * Thuật toán thông minh tự động trích xuất các cột mốc từ văn bản Sách giáo khoa
 */
export function extractMilestonesFromTextbook(content, lessonTitle = '') {
  if (!content || typeof content !== 'string') return [];
  const milestones = [];

  // Regex nhận diện các mốc thời gian lịch sử phổ biến:
  // VD: Ngày 24 - 10 - 1945, năm 1945, tháng 8 - 1945, thế kỉ XX, năm 1010...
  const dateRegex = /(?:ngày\s+)?(\d{1,2}\s*[-–]\s*\d{1,2}\s*[-–]\s*\d{4}|\d{1,2}\s*[-–]\s*\d{4}|tháng\s+\d{1,2}\s*[-–]\s*\d{4}|năm\s+\d{3,4}|thế kỉ\s+[IVXLCDM]+|\b\d{4}\b)/gi;

  const lines = content.split('\n').filter((l) => l.trim().length > 20);

  let counter = 1;
  const seenTimes = new Set();

  for (const line of lines) {
    if (milestones.length >= 8) break; // Lấy tối đa 8 mốc quan trọng nhất
    const cleanLine = line.replace(/[*#>`]/g, '').trim();
    const match = cleanLine.match(dateRegex);

    if (match) {
      const timeStr = match[0].trim();
      if (!seenTimes.has(timeStr)) {
        seenTimes.add(timeStr);

        // Trích xuất tên thực thể hoặc câu ngắn
        let entity = cleanLine.slice(0, 70);
        if (cleanLine.includes(':')) {
          entity = cleanLine.split(':')[0].trim();
        } else if (cleanLine.includes(' - ')) {
          entity = cleanLine.split(' - ')[0].trim();
        }

        // Tự động gán nhãn dựa theo từ khoá
        let typeTag = '#Sự_kiện';
        if (/hiệp ước|hiến chương|tuyên bố|tuyên ngôn|nghị quyết|chỉ thị/i.test(cleanLine)) typeTag = '#Văn_kiện';
        else if (/liên hợp quốc|asean|đảng|hội đồng|quân đội|mặt trận/i.test(cleanLine)) typeTag = '#Tổ_chức';
        else if (/chiến dịch|khởi nghĩa|tổng tiến công|trận/i.test(cleanLine)) typeTag = '#Chiến_dịch';

        let spaceTag = '#Việt_Nam';
        if (/châu âu|pháp|anh|đức|ý/i.test(cleanLine)) spaceTag = '#Châu_Âu';
        else if (/đông nam á|thái lan|in-đô|ma-lai|phi-líp-pin|xin-ga-po/i.test(cleanLine)) spaceTag = '#Đông_Nam_Á';
        else if (/mỹ|hoa kỳ|châu mỹ/i.test(cleanLine)) spaceTag = '#Châu_Mỹ';
        else if (/toàn cầu|quốc tế|thế giới/i.test(cleanLine)) spaceTag = '#Toàn_cầu';

        let eraTag = '#1919-1945';
        if (/1946|1947|1950|1954|pháp/i.test(cleanLine)) eraTag = '#Chống_Pháp';
        else if (/1959|1960|1965|1968|1972|1973|1975|mỹ/i.test(cleanLine)) eraTag = '#Chống_Mỹ';
        else if (/1986|1991|1995|2007|2015|đổi mới/i.test(cleanLine)) eraTag = '#Đổi_mới';
        else if (/tcn|thế kỉ x|thế kỉ xv|ngô quyền|lý|trần|lê|nguyễn/i.test(cleanLine)) eraTag = '#Phong_kiến';

        milestones.push({
          id: `ms-auto-${counter++}`,
          time: timeStr,
          entityName: entity || `Sự kiện gắn liền mốc ${timeStr}`,
          note: cleanLine.slice(0, 120) + '...',
          typeTag,
          spaceTag,
          eraTag,
          customTags: ['#Trích_từ_SGK'],
        });
      }
    }
  }

  return milestones;
}

/**
 * Hàm tra cứu cột mốc tự động theo tiêu đề bài học hoặc nội dung bài học
 * Dùng thống nhất cho TẤT CẢ các bài học của Lớp 10, 11, 12
 */
export function getStandardMilestonesForLesson(lessonTitle = '', chapterTitle = '', content = '') {
  const normTitle = (lessonTitle + ' ' + chapterTitle).toLowerCase();

  // 1. Tra cứu theo từ khoá chủ đề chính xác
  for (const [key, list] of Object.entries(CURRICULUM_MILESTONES_DB)) {
    if (normTitle.includes(key)) {
      return list;
    }
  }

  // 2. Tra cứu theo số bài lớp 12 (Bài 1, Bài 2, ...)
  if (normTitle.includes('bài 1') && normTitle.includes('liên hợp')) return CURRICULUM_MILESTONES_DB['liên hợp quốc'];
  if (normTitle.includes('bài 2') || normTitle.includes('hai cực') || normTitle.includes('i-an-ta')) return CURRICULUM_MILESTONES_DB['chiến tranh lạnh'];
  if (normTitle.includes('bài 3') || normTitle.includes('sau chiến tranh lạnh')) return CURRICULUM_MILESTONES_DB['chiến tranh lạnh'];
  if (normTitle.includes('bài 4') || normTitle.includes('bài 5') || normTitle.includes('cộng đồng asean')) return CURRICULUM_MILESTONES_DB['asean'];
  if (normTitle.includes('bài 6') || normTitle.includes('tháng tám')) return CURRICULUM_MILESTONES_DB['cách mạng tháng tám'];
  if (normTitle.includes('bài 7') || normTitle.includes('chống pháp') || normTitle.includes('điện biên phủ')) return CURRICULUM_MILESTONES_DB['kháng chiến chống thực dân pháp'];
  if (normTitle.includes('bài 8') || normTitle.includes('chống mỹ') || normTitle.includes('xuân 1975')) return CURRICULUM_MILESTONES_DB['kháng chiến chống mỹ'];
  if (normTitle.includes('bài 9') || normTitle.includes('sau tháng 4') || normTitle.includes('gạc ma') || normTitle.includes('tây nam')) return CURRICULUM_MILESTONES_DB['bảo vệ tổ quốc sau 1975'];
  if (normTitle.includes('bài 10') || normTitle.includes('bài 11') || normTitle.includes('đổi mới')) return CURRICULUM_MILESTONES_DB['công cuộc đổi mới'];
  if (normTitle.includes('bài 12') || normTitle.includes('bài 13') || normTitle.includes('bài 14') || normTitle.includes('đối ngoại')) return CURRICULUM_MILESTONES_DB['đối ngoại việt nam'];
  if (normTitle.includes('bài 15') || normTitle.includes('bài 16') || normTitle.includes('bài 17') || normTitle.includes('hồ chí minh')) return CURRICULUM_MILESTONES_DB['hồ chí minh'];

  // Lớp 11
  if (normTitle.includes('cách mạng tư sản')) return CURRICULUM_MILESTONES_DB['cách mạng tư sản'];
  if (normTitle.includes('xô viết') || normTitle.includes('chủ nghĩa xã hội')) return CURRICULUM_MILESTONES_DB['liên bang xô viết'];
  if (normTitle.includes('bảo vệ tổ quốc') || normTitle.includes('khởi nghĩa')) return CURRICULUM_MILESTONES_DB['chiến tranh bảo vệ tổ quốc'];
  if (normTitle.includes('cải cách') || normTitle.includes('hồ quý ly') || normTitle.includes('lê thánh tông') || normTitle.includes('minh mạng')) return CURRICULUM_MILESTONES_DB['cải cách lớn'];
  if (normTitle.includes('biển đông')) return CURRICULUM_MILESTONES_DB['biển đông'];

  // Lớp 10
  if (normTitle.includes('văn minh phương đông') || normTitle.includes('văn minh phương tây') || normTitle.includes('văn minh ai cập')) return CURRICULUM_MILESTONES_DB['văn minh phương đông'];
  if (normTitle.includes('cách mạng công nghiệp')) return CURRICULUM_MILESTONES_DB['cách mạng công nghiệp'];
  if (normTitle.includes('đại việt') || normTitle.includes('thăng long')) return CURRICULUM_MILESTONES_DB['văn minh đại việt'];

  // 3. Nếu chưa khớp từ khoá, tự động trích xuất các mốc từ nội dung sách giáo khoa số
  if (content && content.length > 50) {
    const extracted = extractMilestonesFromTextbook(content, lessonTitle);
    if (extracted.length > 0) return extracted;
  }

  // 4. Mặc định đồng nhất
  return CURRICULUM_MILESTONES_DB['liên hợp quốc'];
}

/**
 * Lấy toàn bộ các mốc lịch sử chuẩn hoá của cả 3 khối lớp 10, 11, 12 gom thành 1 trục niên biểu toàn diện
 */
export function getAllCurriculumMilestones() {
  const all = [];
  const seenEntities = new Set();
  for (const list of Object.values(CURRICULUM_MILESTONES_DB)) {
    for (const m of list) {
      if (!seenEntities.has(m.entityName)) {
        seenEntities.add(m.entityName);
        all.push(m);
      }
    }
  }
  return all;
}
